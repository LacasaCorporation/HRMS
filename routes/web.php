        Route::get('/me', [AuthController::class, 'me']);
        Route::get('/modules', ModuleCatalogController::class);
        Route::get('/dashboard', DashboardController::class);
        Route::get('/employees', [EmployeeController::class, 'index']);
        Route::post('/employees', [EmployeeController::class, 'store']);
        Route::get('/self-service', [EmployeeSelfServiceController::class, 'index']);
        Route::patch('/self-service/profile', [EmployeeSelfServiceController::class, 'updateProfile']);
        Route::get('/expenses', [ExpenseClaimController::class, 'index']);
        Route::post('/expenses', [ExpenseClaimController::class, 'store']);
        Route::post('/expenses/{claim}/review', [ExpenseClaimController::class, 'review']);
        Route::get('/expenses/{claim}/receipt', [ExpenseClaimController::class, 'receipt']);
        Route::get('/loans-advances', [LoanAdvanceController::class, 'index']);
        Route::post('/loans-advances', [LoanAdvanceController::class, 'store']);
        Route::post('/loans-advances/installments/{installment}/repayments', [LoanAdvanceController::class, 'recordRepayment']);
        Route::post('/loans-advances/{loan}/review', [LoanAdvanceController::class, 'review']);
        Route::get('/travel', [TravelController::class, 'index']);
        Route::post('/travel', [TravelController::class, 'store']);
        Route::post('/travel/{trip}/review', [TravelController::class, 'review']);
        Route::post('/travel/{trip}/post-trip-report', [TravelController::class, 'submitReport']);
        Route::post('/travel/{trip}/reconcile', [TravelController::class, 'reconcile']);
        Route::get('/disciplinary', [DisciplinaryController::class, 'index']);
        Route::post('/disciplinary/cases', [DisciplinaryController::class, 'store']);
        Route::post('/disciplinary/cases/{case}/start-review', [DisciplinaryController::class, 'startReview']);
        Route::post('/disciplinary/cases/{case}/employee-response', [DisciplinaryController::class, 'recordResponse']);
        Route::post('/disciplinary/cases/{case}/resolve', [DisciplinaryController::class, 'resolve']);
        Route::get('/organization', [OrganizationController::class, 'index']);
        Route::post('/organization/departments', [OrganizationController::class, 'storeDepartment']);
        Route::patch('/organization/departments/{department}', [OrganizationController::class, 'updateDepartment']);
        Route::post('/organization/positions', [OrganizationController::class, 'storePosition']);
        Route::post('/organization/positions/{position}/assign', [OrganizationController::class, 'assignPosition']);
        Route::patch('/organization/employees/{employee}/reporting-line', [OrganizationController::class, 'updateReportingLine']);
        Route::get('/recruitment', [RecruitmentController::class, 'index']);
        Route::post('/recruitment/requisitions', [RecruitmentController::class, 'storeRequisition']);
        Route::patch('/recruitment/requisitions/{requisition}/status', [RecruitmentController::class, 'updateRequisitionStatus']);
        Route::post('/recruitment/requisitions/{requisition}/candidates', [RecruitmentController::class, 'storeCandidate']);
        Route::patch('/recruitment/candidates/{candidate}', [RecruitmentController::class, 'updateCandidate']);
        Route::post('/recruitment/candidates/{candidate}/hire', [RecruitmentController::class, 'hireCandidate']);
        Route::get('/attendance', [AttendanceController::class, 'index']);
        Route::get('/attendance/report', [AttendanceController::class, 'report']);
        Route::post('/attendance/check-in', [AttendanceController::class, 'checkIn']);
        Route::post('/attendance/{entry}/check-out', [AttendanceController::class, 'checkOut']);
